namespace UseCases.Test.PasswordReset
{
    public class PasswordResetUseCasesTest
    {
        private const string EMAIL = "maria@micash.com.br";
        private const string NEW_PASSWORD = "NovaSenha1!";

        private readonly User _user = new()
        {
            Id = 7 ,
            Name = "Maria Souza" ,
            Email = EMAIL ,
            PasswordHash = "hash:SenhaAntiga1!" ,
            UserIdentifier = Guid.NewGuid()
        };

        private readonly InMemoryPasswordResetRepository _repository = new();
        private readonly Mock<IUnitOfWork> _unitOfWork = new();
        private readonly Mock<IUserReadOnlyRepository> _users = new();
        private readonly Mock<IUserUpdateOnlyRepository> _userUpdates = new();
        private readonly FakeBackgroundJobService _jobs = new();
        private readonly FakeRedisCacheService _cache = new();
        private readonly FakeEncripter _encripter = new();
        private readonly Mock<ITransactionalEmailService> _emails = new();
        private readonly MutableTimeProvider _time = new(new DateTimeOffset(2026 , 11 , 2 , 12 , 0 , 0 , TimeSpan.Zero));
        private readonly List<PasswordRecoveryEmail> _sentCodes = [];

        public PasswordResetUseCasesTest ()
        {
            _repository.Users[_user.Id] = _user;
            _users.Setup(u => u.GetUserByEmail(EMAIL)).ReturnsAsync(_user);
            _users.Setup(u => u.GetByIdAsync(_user.Id , It.IsAny<CancellationToken>())).ReturnsAsync(_user);
            _userUpdates.Setup(u => u.GetById(_user.Id)).ReturnsAsync(_user);

            _emails.Setup(e => e.SendAsync(It.IsAny<string>() , It.IsAny<TransactionalEmail>() , It.IsAny<string?>() , It.IsAny<CancellationToken>()))
                .Callback<string , TransactionalEmail , string? , CancellationToken>(( _ , email , _ , _ ) => {
                    if ( email is PasswordRecoveryEmail recovery ) _sentCodes.Add(recovery);
                })
                .ReturnsAsync("email-id");
        }

        // ---------------- Step 1: request ----------------

        [Fact]
        public async Task Registered_Email_Creates_A_Request_And_Queues_The_Email ()
        {
            var response = await Request(EMAIL);

            response.Should().BeEquivalentTo(RequestPasswordResetUseCase.Response());
            var created = _repository.Requests.Should().ContainSingle().Subject;
            created.UserId.Should().Be(_user.Id);
            created.CodeHash.Should().BeNull("the code is generated by the job, never in the request");
            created.ExpiresAt.Should().Be(_time.UtcNow + PasswordResetRules.CodeValidity);
            _jobs.EnqueuedPasswordResetEmails.Should().Equal(created.Id);
        }

        [Fact]
        public async Task Unregistered_Email_Gets_The_Same_Answer_And_Nothing_Happens ()
        {
            var registered = await Request(EMAIL);
            _time.Advance(TimeSpan.FromMinutes(5));

            var unregistered = await Request("ninguem@micash.com.br");

            unregistered.Should().BeEquivalentTo(registered);
            _repository.Requests.Should().ContainSingle();
            _jobs.EnqueuedPasswordResetEmails.Should().ContainSingle();
        }

        [Fact]
        public async Task Invalid_Email_Format_Is_Refused ()
        {
            var act = () => Request("nao-e-email");

            (await act.Should().ThrowAsync<ErrorOnValidationException>())
                .Which.GetErrors().Should().ContainSingle(ResourceErrorMessages.EMAIL_INVALID);
        }

        [Fact]
        public async Task Resend_Within_The_Interval_Is_Ignored_With_The_Same_Answer ()
        {
            await Request(EMAIL);
            _time.Advance(PasswordResetRules.ResendInterval - TimeSpan.FromSeconds(1));

            var response = await Request(EMAIL);

            response.Should().BeEquivalentTo(RequestPasswordResetUseCase.Response());
            _repository.Requests.Should().ContainSingle();
        }

        [Fact]
        public async Task Resend_After_The_Interval_Replaces_The_Previous_Code ()
        {
            await Request(EMAIL);
            await RunEmailJob();
            _time.Advance(PasswordResetRules.ResendInterval);

            await Request(EMAIL);

            _repository.Requests.Should().HaveCount(2);
            _repository.Requests[0].InvalidatedAt.Should().Be(_time.UtcNow);
            _repository.Requests[1].IsOpen.Should().BeTrue();
            _jobs.EnqueuedPasswordResetEmails.Should().HaveCount(2);
        }

        [Fact]
        public async Task Hourly_Limit_Stops_New_Codes_Until_The_Hour_Passes ()
        {
            for ( var i = 0; i < PasswordResetRules.MAX_REQUESTS_PER_HOUR; i++ ) {
                await Request(EMAIL);
                _time.Advance(PasswordResetRules.ResendInterval);
            }

            await Request(EMAIL);
            _repository.Requests.Should().HaveCount(PasswordResetRules.MAX_REQUESTS_PER_HOUR);

            _time.Advance(TimeSpan.FromHours(1));
            await Request(EMAIL);
            _repository.Requests.Should().HaveCount(PasswordResetRules.MAX_REQUESTS_PER_HOUR + 1);
        }

        [Fact]
        public async Task Queue_Failure_Still_Answers_Normally ()
        {
            _jobs.ThrowOnEnqueue = true;

            var response = await Request(EMAIL);

            response.Should().BeEquivalentTo(RequestPasswordResetUseCase.Response());
        }

        // ---------------- E-mail job (code generation) ----------------

        [Fact]
        public async Task Job_Generates_A_Six_Digit_Code_Stores_Only_Its_Hash_And_Emails_It ()
        {
            await Request(EMAIL);

            await RunEmailJob();

            var sent = _sentCodes.Should().ContainSingle().Subject;
            sent.Code.Should().MatchRegex(@"^\d{6}$");
            sent.Name.Should().Be(_user.Name);
            sent.ValidityMinutes.Should().Be((int)PasswordResetRules.CodeValidity.TotalMinutes);

            var stored = _repository.Requests.Single();
            stored.CodeHash.Should().Be($"hash:{sent.Code}").And.NotBe(sent.Code);
            stored.CodeSentAt.Should().Be(_time.UtcNow);
            _emails.Verify(e => e.SendAsync(EMAIL , It.IsAny<PasswordRecoveryEmail>() , null , It.IsAny<CancellationToken>()) , Times.Once);
        }

        [Fact]
        public async Task Codes_Are_Random ()
        {
            var codes = Enumerable.Range(0 , 50).Select(_ => PasswordResetRules.NewCode()).ToList();

            codes.Should().OnlyContain(c => c.Length == 6 && c.All(char.IsDigit));
            codes.Distinct().Should().HaveCountGreaterThan(40);
        }

        [Fact]
        public async Task Job_Skips_Replaced_Or_Expired_Requests ()
        {
            await Request(EMAIL);
            _repository.Requests[0].InvalidatedAt = _time.UtcNow;
            await RunEmailJob();

            _time.Advance(PasswordResetRules.ResendInterval);
            await Request(EMAIL);
            _time.Advance(PasswordResetRules.CodeValidity);
            await RunEmailJob(_repository.Requests[1].Id);

            _sentCodes.Should().BeEmpty();
        }

        [Fact]
        public async Task Job_Rethrows_Temporary_Failures_And_Gives_Up_On_Permanent_Ones ()
        {
            await Request(EMAIL);

            _emails.Setup(e => e.SendAsync(It.IsAny<string>() , It.IsAny<TransactionalEmail>() , It.IsAny<string?>() , It.IsAny<CancellationToken>()))
                .ThrowsAsync(new EmailServiceException("RateLimitExceeded" , isTransient: true , "x"));
            await FluentActions.Invoking(() => RunEmailJob()).Should().ThrowAsync<EmailServiceException>();

            _emails.Setup(e => e.SendAsync(It.IsAny<string>() , It.IsAny<TransactionalEmail>() , It.IsAny<string?>() , It.IsAny<CancellationToken>()))
                .ThrowsAsync(new EmailServiceException("ValidationError" , isTransient: false , "x"));
            await FluentActions.Invoking(() => RunEmailJob()).Should().NotThrowAsync();
        }

        // ---------------- Step 2: verify ----------------

        [Fact]
        public async Task Correct_Code_Returns_A_Single_Use_Reset_Token ()
        {
            var code = await CodeSent();

            var response = await Verify(code);

            response.ResetToken.Should().NotBeNullOrWhiteSpace();
            response.ExpiresInMinutes.Should().Be((int)PasswordResetRules.ResetTokenValidity.TotalMinutes);

            var stored = _repository.Requests.Single();
            stored.VerifiedAt.Should().Be(_time.UtcNow);
            stored.ResetTokenHash.Should().Be(PasswordResetRules.HashResetToken(response.ResetToken)).And.NotBe(response.ResetToken);
            stored.ResetTokenExpiresAt.Should().Be(_time.UtcNow + PasswordResetRules.ResetTokenValidity);
        }

        [Fact]
        public async Task Wrong_Code_Is_Refused_And_Counted ()
        {
            var code = await CodeSent();

            await ExpectInvalidCode(() => Verify(Other(code)));

            _repository.Requests.Single().Attempts.Should().Be(1);
            _repository.Requests.Single().VerifiedAt.Should().BeNull();
        }

        [Fact]
        public async Task Expired_Code_Is_Refused ()
        {
            var code = await CodeSent();
            _time.Advance(PasswordResetRules.CodeValidity);

            await ExpectInvalidCode(() => Verify(code));
        }

        [Fact]
        public async Task Code_Cannot_Be_Used_Twice ()
        {
            var code = await CodeSent();
            await Verify(code);

            await ExpectInvalidCode(() => Verify(code));
        }

        [Fact]
        public async Task After_Max_Attempts_Even_The_Right_Code_Fails ()
        {
            var code = await CodeSent();

            for ( var i = 0; i < PasswordResetRules.MAX_ATTEMPTS; i++ ) {
                await ExpectInvalidCode(() => Verify(Other(code)));
            }

            _repository.Requests.Single().InvalidatedAt.Should().NotBeNull();
            await ExpectInvalidCode(() => Verify(code));
        }

        [Fact]
        public async Task Unknown_Email_Gets_The_Same_Error ()
        {
            await ExpectInvalidCode(() => Verify("123456" , "ninguem@micash.com.br"));
        }

        [Fact]
        public async Task Previous_Code_Stops_Working_After_A_New_One ()
        {
            var first = await CodeSent();
            _time.Advance(PasswordResetRules.ResendInterval);
            var second = await CodeSent();

            if ( first != second ) {
                await ExpectInvalidCode(() => Verify(first));
            }

            (await Verify(second)).ResetToken.Should().NotBeNullOrWhiteSpace();
        }

        [Fact]
        public async Task Concurrent_Update_Is_A_Failure_Not_A_Free_Attempt ()
        {
            var code = await CodeSent();
            _unitOfWork.Setup(u => u.Commit(It.IsAny<CancellationToken>())).ThrowsAsync(new ConflictException());

            await ExpectInvalidCode(() => Verify(code));
        }

        [Theory]
        [InlineData("12345")]
        [InlineData("abcdef")]
        [InlineData("")]
        public async Task Code_Format_Is_Validated ( string code )
        {
            var act = () => Verify(code);

            (await act.Should().ThrowAsync<ErrorOnValidationException>())
                .Which.GetErrors().Should().Contain(ResourceErrorMessages.PASSWORD_RESET_CODE_FORMAT);
        }

        // ---------------- Step 3: reset ----------------

        [Fact]
        public async Task Valid_Token_Changes_The_Password_And_Closes_The_Request ()
        {
            var token = (await Verify(await CodeSent())).ResetToken;

            await Reset(token , NEW_PASSWORD);

            _user.PasswordHash.Should().Be($"hash:{NEW_PASSWORD}");
            _userUpdates.Verify(u => u.Update(_user) , Times.Once);
            _repository.Requests.Single().CompletedAt.Should().Be(_time.UtcNow);
            _repository.Requests.Single().IsOpen.Should().BeFalse();

            (await _cache.GetAsync<PasswordChangedData>(PasswordChangedData.Key(_user.UserIdentifier)))!
                .ChangedAt.Should().Be(_time.UtcNow);

            // The code reached the mailbox: an unverified account becomes verified.
            _user.EmailVerifiedAt.Should().Be(_time.UtcNow);
        }

        [Fact]
        public async Task Reset_Keeps_The_Original_Verification_Date ()
        {
            var verifiedAt = _time.UtcNow.AddDays(-30);
            _user.EmailVerifiedAt = verifiedAt;
            var token = (await Verify(await CodeSent())).ResetToken;

            await Reset(token , NEW_PASSWORD);

            _user.EmailVerifiedAt.Should().Be(verifiedAt);
        }

        [Fact]
        public async Task New_Password_Equal_To_The_Current_One_Is_Refused_Without_Using_The_Token ()
        {
            var token = (await Verify(await CodeSent())).ResetToken;

            var act = () => Reset(token , "SenhaAntiga1!");

            (await act.Should().ThrowAsync<ErrorOnValidationException>())
                .Which.GetErrors().Should().ContainSingle(ResourceErrorMessages.NEW_PASSWORD_SAME_AS_CURRENT);
            _repository.Requests.Single().CompletedAt.Should().BeNull();
            _userUpdates.Verify(u => u.Update(It.IsAny<User>()) , Times.Never);

            await Reset(token , NEW_PASSWORD);
            _user.PasswordHash.Should().Be($"hash:{NEW_PASSWORD}");
        }

        [Fact]
        public async Task Token_Cannot_Be_Used_Twice ()
        {
            var token = (await Verify(await CodeSent())).ResetToken;
            await Reset(token , NEW_PASSWORD);

            await ExpectInvalidToken(() => Reset(token , "OutraSenha2!"));
            _user.PasswordHash.Should().Be($"hash:{NEW_PASSWORD}");
        }

        [Fact]
        public async Task Unknown_Token_Is_Refused ()
        {
            await ExpectInvalidToken(() => Reset("token-inventado" , NEW_PASSWORD));
        }

        [Fact]
        public async Task Expired_Token_Is_Refused ()
        {
            var token = (await Verify(await CodeSent())).ResetToken;
            _time.Advance(PasswordResetRules.ResetTokenValidity);

            await ExpectInvalidToken(() => Reset(token , NEW_PASSWORD));
            _user.PasswordHash.Should().Be("hash:SenhaAntiga1!");
        }

        [Fact]
        public async Task Token_Of_A_Replaced_Request_Is_Refused ()
        {
            var token = (await Verify(await CodeSent())).ResetToken;
            _time.Advance(PasswordResetRules.ResendInterval);
            await Request(EMAIL);

            await ExpectInvalidToken(() => Reset(token , NEW_PASSWORD));
        }

        [Fact]
        public async Task Weak_Password_Is_Refused_Without_Using_The_Token ()
        {
            var token = (await Verify(await CodeSent())).ResetToken;

            var act = () => Reset(token , "fraca");

            (await act.Should().ThrowAsync<ErrorOnValidationException>())
                .Which.GetErrors().Should().Contain(ResourceErrorMessages.INVALID_PASSWORD);
            _repository.Requests.Single().CompletedAt.Should().BeNull();

            await Reset(token , NEW_PASSWORD);
        }

        // ---------------- Sessions after the reset ----------------

        [Fact]
        public async Task Refresh_Tokens_Issued_Before_The_Reset_Are_Refused ()
        {
            await _cache.SetAsync("refreshToken:old" , new RefreshTokenData
            {
                UserIdentifier = _user.UserIdentifier ,
                Token = "old" ,
                IssuedAt = _time.UtcNow.AddMinutes(-1) ,
                ExpiresAt = _time.UtcNow.AddDays(7)
            });

            var token = (await Verify(await CodeSent())).ResetToken;
            await Reset(token , NEW_PASSWORD);

            await _cache.SetAsync("refreshToken:new" , new RefreshTokenData
            {
                UserIdentifier = _user.UserIdentifier ,
                Token = "new" ,
                IssuedAt = _time.UtcNow.AddSeconds(1) ,
                ExpiresAt = _time.UtcNow.AddDays(7)
            });

            var userRepository = new Mock<IUserReadOnlyRepository>();
            userRepository.Setup(u => u.GetByUserIdentifier(_user.UserIdentifier)).ReturnsAsync(_user);
            var refresh = new RefreshTokenUseCase(
                _cache , userRepository.Object , Mock.Of<IAccessTokenGenerator>() ,
                Mock.Of<IRefreshTokenGenerator>(g => g.Generate() == "next"));

            await FluentActions.Invoking(() => refresh.Execute(new RequestRefreshTokenJson { RefreshToken = "old" }))
                .Should().ThrowAsync<InvalidTokenException>();
            (await _cache.GetAsync<RefreshTokenData>("refreshToken:old")).Should().BeNull();

            await FluentActions.Invoking(() => refresh.Execute(new RequestRefreshTokenJson { RefreshToken = "new" }))
                .Should().NotThrowAsync();
        }

        // ---------------- Welcome e-mail ----------------

        [Fact]
        public async Task Welcome_Job_Sends_The_Template_With_The_User_Name ()
        {
            await WelcomeJob().ExecuteAsync(_user.Id , CancellationToken.None);

            _emails.Verify(e => e.SendAsync(
                EMAIL ,
                It.Is<WelcomeEmail>(w => w.Name == _user.Name) ,
                $"welcome-{_user.Id}" ,
                It.IsAny<CancellationToken>()) , Times.Once);
        }

        [Fact]
        public async Task Welcome_Job_Retries_Only_Temporary_Failures ()
        {
            _emails.Setup(e => e.SendAsync(It.IsAny<string>() , It.IsAny<TransactionalEmail>() , It.IsAny<string?>() , It.IsAny<CancellationToken>()))
                .ThrowsAsync(new EmailServiceException("Timeout" , isTransient: true , "x"));
            await FluentActions.Invoking(() => WelcomeJob().ExecuteAsync(_user.Id , CancellationToken.None))
                .Should().ThrowAsync<EmailServiceException>();

            _emails.Setup(e => e.SendAsync(It.IsAny<string>() , It.IsAny<TransactionalEmail>() , It.IsAny<string?>() , It.IsAny<CancellationToken>()))
                .ThrowsAsync(new EmailServiceException("InvalidFromAddress" , isTransient: false , "x"));
            await FluentActions.Invoking(() => WelcomeJob().ExecuteAsync(_user.Id , CancellationToken.None))
                .Should().NotThrowAsync();
        }

        [Fact]
        public async Task Welcome_Job_Skips_Deleted_Users ()
        {
            await WelcomeJob().ExecuteAsync(999 , CancellationToken.None);

            _emails.VerifyNoOtherCalls();
        }

        // ---------------- helpers ----------------

        private Task<MiCash.Communication.Responses.PasswordReset.ResponseForgotPasswordJson> Request ( string email ) =>
            new RequestPasswordResetUseCase(
                _users.Object , _repository , _repository , _repository , _unitOfWork.Object , _jobs , _time ,
                NullLogger<RequestPasswordResetUseCase>.Instance)
            .Execute(new RequestForgotPasswordJson { Email = email } , CancellationToken.None);

        private Task RunEmailJob ( long? id = null ) =>
            new PasswordResetEmailJob(_repository , _unitOfWork.Object , _encripter , _emails.Object , _time ,
                NullLogger<PasswordResetEmailJob>.Instance)
            .ExecuteAsync(id ?? _repository.Requests.Last().Id , CancellationToken.None);

        private async Task<string> CodeSent ()
        {
            await Request(EMAIL);
            await RunEmailJob();
            return _sentCodes.Last().Code;
        }

        private Task<MiCash.Communication.Responses.PasswordReset.ResponsePasswordResetCodeVerifiedJson> Verify ( string code , string email = EMAIL ) =>
            new VerifyPasswordResetCodeUseCase(_users.Object , _repository , _unitOfWork.Object , _encripter , _time ,
                NullLogger<VerifyPasswordResetCodeUseCase>.Instance)
            .Execute(new RequestVerifyPasswordResetCodeJson { Email = email , Code = code } , CancellationToken.None);

        private Task Reset ( string token , string password ) =>
            new ResetPasswordUseCase(_repository , _userUpdates.Object , _unitOfWork.Object , _encripter , _cache , _time ,
                NullLogger<ResetPasswordUseCase>.Instance)
            .Execute(new RequestResetPasswordJson { ResetToken = token , NewPassword = password } , CancellationToken.None);

        private WelcomeEmailJob WelcomeJob () =>
            new(_users.Object , _emails.Object , NullLogger<WelcomeEmailJob>.Instance);

        private static async Task ExpectInvalidCode ( Func<Task> act ) =>
            (await act.Should().ThrowAsync<ErrorOnValidationException>())
                .Which.GetErrors().Should().ContainSingle(ResourceErrorMessages.PASSWORD_RESET_CODE_INVALID);

        private static async Task ExpectInvalidToken ( Func<Task> act ) =>
            (await act.Should().ThrowAsync<ErrorOnValidationException>())
                .Which.GetErrors().Should().ContainSingle(ResourceErrorMessages.PASSWORD_RESET_TOKEN_INVALID);

        private static string Other ( string code ) => code == "000000" ? "111111" : "000000";

        /// <summary>Deterministic stand-in for BCrypt: "hash:" + value.</summary>
        private sealed class FakeEncripter : IPasswordEncripter
        {
            public string Encrypt ( string password ) => $"hash:{password}";

            public bool Verify ( string password , string passwordHash ) => passwordHash == $"hash:{password}";
        }
    }
