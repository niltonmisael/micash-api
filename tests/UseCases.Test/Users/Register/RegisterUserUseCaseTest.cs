using CommonTestUtilities.Cache;
using CommonTestUtilities.Cryptography;
using CommonTestUtilities.Jobs;
using CommonTestUtilities.Repositories;
using CommonTestUtilities.Requests;
using CommonTestUtilities.Token;
using FluentAssertions;
using MiCash.Application.UseCases.Auth.EmailVerification;
using MiCash.Application.UseCases.Users.Register;
using MiCash.Exception;
using MiCash.Exception.ExceptionBase;
using Microsoft.Extensions.Logging.Abstractions;

namespace UseCases.Test.Users.Register
{
    public class RegisterUserUseCaseTest
    {
        private readonly InMemoryEmailVerificationRepository _verifications = new();

        [Fact]
        public async Task Success ()
        {
            var cancellationToken = CancellationToken.None;
            var request = RequestRegisterUserJsonBuilder.Build();
            var useCase = CreateUseCase();

            var result = await useCase.Execute(request, cancellationToken);

            result.Should().NotBeNull();
            result.Name.Should().Be(request.Name);
            result.RefreshToken.Should().NotBeNullOrWhiteSpace();
            result.Token.Should().NotBeNullOrWhiteSpace();
            result.EmailVerified.Should().BeFalse("the account starts unverified");
        }

        [Fact]
        public async Task Error_Name_Empty ()
        {
            var cancellationToken = CancellationToken.None;
            var request = RequestRegisterUserJsonBuilder.Build();
            request.Name = string.Empty;

            var useCase = CreateUseCase();

            var act = async () => await useCase.Execute(request, cancellationToken);

            var result = await act.Should().ThrowAsync<ErrorOnValidationException>();

            result.Where(ex => ex.GetErrors().Count == 1 && ex.GetErrors().Contains(ResourceErrorMessages.NAME_EMPTY));
        }

        [Fact]
        public async Task Error_Email_Already_Exist ()
        {

            var cancellationToken = CancellationToken.None;
            var request = RequestRegisterUserJsonBuilder.Build();

            var useCase = CreateUseCase(request.Email);

            var act = async () => await useCase.Execute(request, cancellationToken);

            var result = await act.Should().ThrowAsync<ErrorOnValidationException>();

            result.Where(ex => ex.GetErrors().Count == 1 && ex.GetErrors().Contains(ResourceErrorMessages.EMAIL_ALREADY_REGISTERED));
        }

        [Fact]
        public async Task Verification_Code_Is_Queued_Instead_Of_The_Welcome_Email ()
        {
            var jobs = new FakeBackgroundJobService();
            var request = RequestRegisterUserJsonBuilder.Build();

            await CreateUseCase(jobs: jobs).Execute(request , CancellationToken.None);

            var verification = _verifications.Requests.Should().ContainSingle().Subject;
            verification.Email.Should().Be(request.Email);
            verification.CodeHash.Should().BeNull("the code is generated by the job, never in the request");
            jobs.EnqueuedEmailVerificationEmails.Should().Equal(verification.Id);
            jobs.EnqueuedWelcomeEmails.Should().BeEmpty("the welcome e-mail goes after the confirmation");
        }

        [Fact]
        public async Task Registration_Succeeds_Even_If_The_Code_Cannot_Be_Queued ()
        {
            var jobs = new FakeBackgroundJobService { ThrowOnEnqueue = true };
            var request = RequestRegisterUserJsonBuilder.Build();

            var result = await CreateUseCase(jobs: jobs).Execute(request , CancellationToken.None);

            result.Name.Should().Be(request.Name);
            result.Token.Should().NotBeNullOrWhiteSpace();
            jobs.EnqueuedEmailVerificationEmails.Should().BeEmpty();
        }

        [Fact]
        public async Task Invalid_Registration_Does_Not_Queue_A_Code ()
        {
            var jobs = new FakeBackgroundJobService();
            var request = RequestRegisterUserJsonBuilder.Build();
            request.Name = string.Empty;

            var act = () => CreateUseCase(jobs: jobs).Execute(request , CancellationToken.None);

            await act.Should().ThrowAsync<ErrorOnValidationException>();
            jobs.EnqueuedEmailVerificationEmails.Should().BeEmpty();
            _verifications.Requests.Should().BeEmpty();
        }

        private RegisterUserUseCase CreateUseCase ( string? email = null , FakeBackgroundJobService? jobs = null )
        {
            var passwordEncripter = new PasswordEncrypterBuilder().Build();
            var writeRepository = UserWriteOnlyRepositoryBuilder.Build();
            var unitOfWork = UnitOfWorkBuilder.Build();
            var tokenGenerator = JwtTokenGeneratorBuilder.Build();
            var readRepository = new UserReadOnlyRepositoryBuilder();
            var refreshTokenGenerator = RefreshTokenGeneratorBuilder.Build();
            var redisCacheService = new RedisCacheServiceBuilder();

            if ( string.IsNullOrWhiteSpace(email) == false) {
                readRepository.ExistActiveUserWithEmail(email);
            }

            var issuer = new EmailVerificationCodeIssuer(
                _verifications , _verifications , _verifications ,
                jobs ?? new FakeBackgroundJobService() ,
                NullLogger<EmailVerificationCodeIssuer>.Instance);

            return new RegisterUserUseCase(
                passwordEncripter, 
                readRepository.Build(), 
                writeRepository , 
                unitOfWork , 
                tokenGenerator,
                refreshTokenGenerator,
                redisCacheService.Build() ,
                issuer ,
                TimeProvider.System
                );

        }

    }
}
